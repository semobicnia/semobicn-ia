import {
  forwardRef,
  type HTMLAttributes,
} from "react";
import { cn } from "@/lib/utils";

export const Card = forwardRef<HTMLDivElement, HTMLAttributes<HTMLDivElement>>(
  ({ className, ...props }, ref) => (
    <div
      ref={ref}
      className={cn(
        "rounded-2xl border border-zinc-200/80 bg-white text-zinc-950 shadow-sm",
        className,
      )}
      {...props}
    />
  ),
);
Card.displayName = "Card";

